            else -> raw
        }
        "شکل‌محور" -> when (this) {
            StringsAr -> "قائم على الشكل"
            StringsEn -> "Diagram-Based"
            else -> raw
        }
        else -> raw
    }

    fun localizeModeName(storedMode: String): String = when (storedMode) {
        QuizMode.TIMED_KONKUR.titleFa, QuizMode.TIMED_KONKUR.name -> modeTimedTitle
        QuizMode.FREE_STUDY.titleFa, QuizMode.FREE_STUDY.name -> modeFreeTitle
        QuizMode.REVIEW_MISTAKES.titleFa, QuizMode.REVIEW_MISTAKES.name -> modeReviewTitle
        else -> storedMode
    }

    companion object {
        fun forLanguage(language: AppLanguage): AppStrings = when (language) {
            AppLanguage.FA -> StringsFa
            AppLanguage.AR -> StringsAr
            AppLanguage.EN -> StringsEn
        }
    }
