    fun modeTitle(mode: QuizMode): String = when (mode) {
        QuizMode.TIMED_KONKUR -> modeTimedTitle
        QuizMode.FREE_STUDY -> modeFreeTitle
        QuizMode.REVIEW_MISTAKES -> modeReviewTitle
    }

    fun modeSubtitle(mode: QuizMode): String = when (mode) {
        QuizMode.TIMED_KONKUR -> modeTimedSub
        QuizMode.FREE_STUDY -> modeFreeSub
        QuizMode.REVIEW_MISTAKES -> modeReviewSub
    }

    fun localizeDifficulty(raw: String): String = when (raw) {
        "دام کنکوری" -> diffTrap
        "بسیار سخت" -> diffVeryHard
        "سخت" -> diffHard
        else -> raw
    }

    fun localizeQuestionType(raw: String): String = when (raw) {
        "چندموردی" -> when (this) {
            StringsAr -> "متعدد الخيارات"
            StringsEn -> "Multi-Statement"
            else -> raw
        }
        "مفهومی" -> when (this) {
            StringsAr -> "مفاهيمي"
            StringsEn -> "Conceptual"
            else -> raw
        }
        "مقایسه‌ای" -> when (this) {
            StringsAr -> "مقارنة"
